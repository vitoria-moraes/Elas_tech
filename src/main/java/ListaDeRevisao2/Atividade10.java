package ListaDeRevisao2;

public class Atividade10 {

    public static void mostrarBoasVindas(){
        System.out.println("Boas vindas, Vitória!");
    }
    public static void main(String[] args) {
        /*Enunciado do Exercício: Crie um
        metodo mostrarBoasVindas() que
        imprime uma mensagem. Chame ele no main.*/

        mostrarBoasVindas();

        /*public static void mostrarBoasVindas():
        public e static definem o modificador e o comportamento do metodo.
        O static é necessário para podermos chamá-lo diretamente de dentro
        do main (que também é estático).
        void significa que o metodo não retorna nenhum valor
        (ele apenas executa a ação de imprimir algo na tela).
        mostrarBoasVindas() é o nome que demos ao metodo,
        seguido de parênteses (onde poderíamos colocar parâmetros,
        se fossem necessários).
        Chamada no main: Para o código rodar,
        precisamos "chamar" ou "invocar" o metodo pelo nome dentro do metodo main.*/
    }
}

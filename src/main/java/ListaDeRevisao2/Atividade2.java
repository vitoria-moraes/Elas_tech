package ListaDeRevisao2;

public class Atividade2 {
    public static void main(String[] args) {
        /*Enunciado do Exercício: Crie a = 15 e b = 4.
        Imprima a soma, a subtração, a multiplicação,
        a divisão e o resto.*/

        int a = 15;
        int b = 4;

        System.out.println("Resultado soma : " + (a + b));
        System.out.println("Resultado subtração : " + (a - b));
        System.out.println("Resultado multiplicação : " + (a * b));
        System.out.println("Resultado divisão : " + (a / b));
        System.out.println("Resultado resto : " + (a % b));

    }
}

package EstrtuturasDeRepeticao;

public class For {
    public static void main(String[] args) {

        for(int i = 1; i <= 30; i++){
            System.out.println(i);
        }
        for(int i = 30; i >= 1; i--){
            System.out.println(i);
        }

        System.out.println("Fim!");
    }
}


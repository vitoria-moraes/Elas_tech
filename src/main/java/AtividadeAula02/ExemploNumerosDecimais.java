package AtividadeAula02;

public class ExemploNumerosDecimais {
    public static void main(String[] args) {

        double a = 10.5;
        double b = 3.5;
        double resultado = a + b;

        System.out.println(resultado);

        double c = 10.5;
        double d = 3.5;
        double resultado2 = c - d;

        System.out.println(resultado2);

        double e = 10.5;
        double f = 3.5;
        double resultado3 = e * f;

        System.out.println(resultado3);

        double g = 10.5;
        double h = 3.5;
        double resultado4 = g / h;

        System.out.println(resultado4);

        double i = 10.5;
        double j = 3.5;
        double resultado5 = i % j;

        System.out.println(resultado5);
    }
}
